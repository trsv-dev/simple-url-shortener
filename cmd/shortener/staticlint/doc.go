// Package main реализует собственный multichecker для статического анализа Go-кода.
//
// Staticlint объединяет несколько групп анализаторов:
//
//   - стандартные анализаторы из пакета
//     golang.org/x/tools/go/analysis/passes
//
//   - анализаторы класса SA из staticcheck
//
//   - анализаторы класса ST из stylecheck
//
//   - сторонние публичные анализаторы
//
//   - пользовательский анализатор noexitmain
//
// В состав multichecker входят следующие анализаторы.
//
// Стандартные анализаторы:
//
//   - printf
//     Проверяет корректность форматированных строк и аргументов
//     в функциях fmt.Printf, fmt.Sprintf и аналогичных.
//
//   - structtag
//     Проверяет корректность тегов структур.
//
//   - cgocall
//     Проверяет корректность передачи указателей при использовании cgo.
//
//   - composite
//     Проверяет использование неименованных полей
//     в составных литералах структур.
//
// Сторонние анализаторы:
//
//   - ineffassign
//     Обнаруживает бесполезные присваивания переменным.
//
//   - nilerr
//     Обнаруживает ситуации, когда вместо ошибки
//     возвращается nil.
//
// Анализаторы staticcheck:
//
//   - SA*
//     Набор анализаторов для поиска потенциальных ошибок,
//     багов и подозрительных конструкций в коде.
//
// Анализаторы stylecheck:
//
//   - ST*
//     Анализаторы, проверяющие стиль написания Go-кода.
//
// Пользовательские анализаторы:
//
//   - noexitmain
//     Запрещает прямой вызов os.Exit внутри функции main пакета main.
//
// Сборка multichecker:
//
//	go build -o staticlint ./cmd/shortener/staticlint
//
// Запуск проверки всего проекта:
//
//	./staticlint ./...
//
// Запуск проверки конкретного пакета:
//
//	./staticlint ./internal/...
