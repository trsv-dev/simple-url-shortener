// Package memory реализует in-memory хранилище URL-ов для simple-url-shortener.
//
// Хранилище хранит соответствия длинного URL ↔ короткий URL в оперативной памяти,
// обеспечивает генерацию коротких URL, контроль коллизий и работу с пользователями.
//
// Основные возможности пакета:
//   - Добавление одиночного URL и батчей URL-ов.
//   - Получение длинного URL по короткому.
//   - Получение списка всех URL пользователя.
//   - Пометка URL на удаление и последующая очистка.
//   - Реализация интерфейса Storage без зависимости от внешних ресурсов.
//
// Используется для разработки, тестирования и случаев, когда не требуется
// постоянное хранилище.
package memory
