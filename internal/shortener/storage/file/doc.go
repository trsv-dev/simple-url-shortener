// Package file реализует файловое хранилище URL-ов для simple-url-shortener.
//
// Хранилище сохраняет соответствия длинного URL ↔ короткий URL как в оперативной памяти,
// так и в файловой базе данных. Пакет обеспечивает генерацию коротких URL, контроль коллизий,
// работу с пользователями и восстановление данных при перезапуске.
//
// Основные возможности пакета:
//   - Добавление одиночного URL и батчей URL-ов в память и файл.
//   - Получение длинного URL по короткому.
//   - Получение списка всех URL пользователя.
//   - Пометка URL на удаление и последующая очистка.
//   - Восстановление данных из файла при старте.
//   - Реализация интерфейса Storage с поддержкой "живого" Ping и Close.
//
// Используется для хранения данных между перезапусками сервера и для случаев,
// когда требуется долговременное хранение URL-ов.
package file
