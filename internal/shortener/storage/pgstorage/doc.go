// Package pgstorage реализует хранилище URL-ов на базе PostgreSQL.
//
// Пакет отвечает за работу с базой данных, транзакциями и преобразование ошибок БД
// в доменные ошибки приложения. Он обеспечивает долговременное хранение URL-ов,
// управление пользователями и контроль удалённых записей.
//
// Основные возможности пакета:
//   - Добавление одиночного URL и батчей URL-ов с проверкой коллизий.
//   - Получение оригинального URL по короткому идентификатору.
//   - Получение списка всех URL пользователя.
//   - Пометка URL на удаление и последующая физическая очистка.
//   - Инициализация схемы таблицы и подключение к базе.
//   - Реализация интерфейса Storage с поддержкой Ping и Close.
//
// Используется для обеспечения долговременного хранения URL-ов с поддержкой
// уникальности, управления пользователями и безопасного удаления записей.
